import de.uni_passau.fim.se2.litterbox.utils.ScratchBlocksFormatUtil;

import java.util.*;

/**
 * Abstract base class for question finders that produce {@link Question} objects.
 * Implements {@link QuestionFinder} and provides common visitor functionality.
 *
 * <p>This class serves as the base for question finders that work with the
 * {@link Question} class directly. Subclasses must implement:
 * <ul>
 *   <li>{@link #getName()} - the unique finder name</li>
 *   <li>{@link #getQuestionType()} - the type of answer expected (MULTIPLE_CHOICE, FREE_TEXT, etc.)</li>
 *   <li>{@link #getProgramDimension()} - the program dimension (TEXT, EXECUTION, PURPOSE)</li>
 *   <li>{@link #getScopeOfFocus()} - the scope of focus (ATOM, BLOCK, RELATION, MACRO)</li>
 * </ul>
 *
 * <h2>Naming Conventions</h2>
 *
 * <p>Question finder class names should follow these patterns:
 * <ul>
 *   <li><b>Purpose questions:</b> {@code PurposeOf<Subject>} - e.g., {@code PurposeOfVariable}</li>
 *   <li><b>Execution questions:</b> {@code <Subject>Execution} - e.g., {@code IfThenStatementExecution}</li>
 *   <li><b>Counting questions:</b> {@code <Subject>In<Context>} or {@code <Subject>For<Context>}</li>
 *   <li><b>Relation questions:</b> Descriptive phrases - e.g., {@code BroadcastReceivers}</li>
 *   <li><b>Element presence:</b> {@code ElementIn<Location>} - e.g., {@code ElementInLoopBody}</li>
 * </ul>
 *
 * <h2>State Management</h2>
 *
 * <p>Subclasses with mutable instance fields should override {@link #resetState()} to reset
 * their state, calling {@code super.resetState()} first. This ensures proper behavior when
 * a finder instance is reused across multiple {@link #check(Program)} calls.
 */
public abstract class AbstractQuestionFinder implements QuestionFinder, ScratchVisitor {

    /**
     * Maximum number of choices to include in multiple choice questions.
     */
    protected final int maxChoices;

    /**
     * The actor currently being visited.
     */
    protected ActorDefinition currentActor;

    /**
     * The script currently being visited (null if in a procedure).
     */
    protected Script currentScript;

    /**
     * The procedure currently being visited (null if in a script).
     */
    protected ProcedureDefinition currentProcedure;

    /**
     * The set of questions generated by this finder.
     */
    protected Set<Question> questions = new LinkedHashSet<>();

    /**
     * Procedure mapping for the current actor.
     */
    protected Map<LocalIdentifier, ProcedureInfo> procMap;

    /**
     * The program being analyzed.
     */
    protected Program program;

    /**
     * Whether to skip loose (unconnected) blocks.
     */
    protected boolean ignoreLooseBlocks = false;

    /**
     * Collected choices for multiple choice questions.
     */
    protected Set<String> choices;

    /**
     * Collected correct answers for questions.
     */
    protected Set<String> answers;

    /**
     * Whether currently inside a look statement (for StringLiteral formatting).
     */
    protected boolean inLookStmt;

    /**
     * Whether currently inside a sound statement (for StringLiteral formatting).
     */
    protected boolean inSoundStmt;

    /**
     * Whether currently inside a broadcast statement (for StringLiteral formatting).
     */
    protected boolean inBroadcastStmt;

    /**
     * Creates a new question finder with default settings.
     */
    protected AbstractQuestionFinder() {
        this.maxChoices = 4;
    }

    @Override
    public Set<Question> check(Program program) {
        Preconditions.checkNotNull(program);
        this.program = program;
        resetState();
        program.accept(this);
        return Collections.unmodifiableSet(questions);
    }

    /**
     * Resets all mutable state before a new check.
     * Subclasses with their own mutable state should override this method
     * and call {@code super.resetState()} first.
     */
    protected void resetState() {
        this.currentActor = null;
        this.currentScript = null;
        this.currentProcedure = null;
        this.procMap = null;
        this.inLookStmt = false;
        this.inSoundStmt = false;
        this.inBroadcastStmt = false;
        this.questions = new LinkedHashSet<>();
        this.choices = new LinkedHashSet<>();
        this.answers = new LinkedHashSet<>();
    }

    @Override
    public void visit(ActorDefinition actor) {
        Preconditions.checkNotNull(program);
        currentActor = actor;
        procMap = program.getProcedureMapping().getProceduresForActor(actor.getIdent().getName());
        visitChildren(actor);
    }

    @Override
    public void visit(Script script) {
        if (ignoreLooseBlocks && script.getEvent() instanceof Never) {
            return;
        }
        currentScript = script;
        currentProcedure = null;
        visitChildren(script);
    }

    @Override
    public void visit(ProcedureDefinition procedure) {
        currentProcedure = procedure;
        currentScript = null;
        visitChildren(procedure);
    }

    @Override
    public Collection<String> getHintKeys() {
        return Collections.singletonList(getName());
    }

    @Override
    public void setIgnoreLooseBlocks(boolean value) {
        ignoreLooseBlocks = value;
    }

    /**
     * Creates a new QuestionBuilder pre-populated with common fields.
     *
     * @return a new QuestionBuilder
     */
    protected QuestionBuilder prepareQuestionBuilder() {
        return new QuestionBuilder()
                .withFinder(this)
                .withProgram(program)
                .withActor(currentActor)
                .withScriptOrProcedure(getCurrentScriptEntity())
                .withQuestionType(getQuestionType())
                .withProgramDimension(getProgramDimension())
                .withScopeOfFocus(getScopeOfFocus())
                .withQuestionText(QuestionText.fromKey(getName()));
    }

    /**
     * Creates a new QuestionBuilder pre-populated with common fields and the given node.
     *
     * @param node the AST node for this question
     * @return a new QuestionBuilder
     */
    protected QuestionBuilder prepareQuestionBuilder(ASTNode node) {
        return prepareQuestionBuilder()
                .withCurrentNode(node)
                .withMetadata(node.getMetadata());
    }

    /**
     * Adds a question to the result set.
     *
     * @param builder the question builder
     */
    protected void addQuestion(QuestionBuilder builder) {
        questions.add(builder.build());
    }

    /**
     * Adds a question to the result set.
     *
     * @param question the question to add
     */
    protected void addQuestion(Question question) {
        questions.add(question);
    }

    /**
     * Returns the current script or procedure being visited.
     *
     * @return the current script entity
     */
    protected ScriptEntity getCurrentScriptEntity() {
        if (currentScript != null) {
            return currentScript;
        }
        return currentProcedure;
    }

    // Choice/answer management

    /**
     * Returns the answers, limited to maxChoices if there are more.
     *
     * @return list of answers
     */
    protected List<String> getAnswersList() {
        ArrayList<String> list = new ArrayList<>(answers);
        if (answers.size() > maxChoices) {
            Randomness.shuffle(list);
            return list.subList(0, maxChoices);
        }
        return list;
    }

    /**
     * Generates a robust list of multiple choice options.
     * Ensures all correct answers are included (up to maxChoices) and fills the rest with distractors.
     * The final list is shuffled.
     *
     * @param correctAnswers the correct answers
     * @param distractors    potential distractors (pool)
     * @return shuffled list of options
     */
    protected List<String> generateMultipleChoiceOptions(Collection<String> correctAnswers,
                                                         Collection<String> distractors) {
        return generateOptionsInternal(correctAnswers, distractors);
    }

    /**
     * Generates a robust list of multiple choice options for translatable text.
     * Ensures all correct answers are included (up to maxChoices) and fills the rest with distractors.
     * The final list is shuffled.
     *
     * @param correctAnswers the correct answers
     * @param distractors    potential distractors (pool)
     * @return shuffled list of options
     */
    protected List<TranslatableText> generateTranslatableMultipleChoiceOptions(
            Collection<? extends TranslatableText> correctAnswers,
            Collection<? extends TranslatableText> distractors) {
        return generateOptionsInternal(correctAnswers, distractors);
    }

    /**
     * Generic implementation for generating multiple choice options.
     * Ensures all correct answers are included (up to maxChoices) and fills the rest with distractors.
     * The final list is shuffled.
     *
     * @param <T>            the type of options
     * @param correctAnswers the correct answers
     * @param distractors    potential distractors (pool)
     * @return shuffled list of options
     */
    private <T> List<T> generateOptionsInternal(Collection<? extends T> correctAnswers,
                                                Collection<? extends T> distractors) {
        // Add correct answers first (up to max)
        List<T> correctList = new ArrayList<>(correctAnswers);
        if (correctList.size() > maxChoices) {
            Randomness.shuffle(correctList);
            correctList = correctList.subList(0, maxChoices);
        }
        Set<T> finalChoices = new LinkedHashSet<>(correctList);

        // Fill remaining slots with distractors
        if (finalChoices.size() < maxChoices) {
            List<T> distractorList = new ArrayList<>(distractors);
            distractorList.removeAll(finalChoices); // Don't duplicate correct answers
            Randomness.shuffle(distractorList);

            for (T d : distractorList) {
                if (finalChoices.size() >= maxChoices) {
                    break;
                }
                finalChoices.add(d);
            }
        }

        // Final shuffle for display order
        List<T> result = new ArrayList<>(finalChoices);
        Randomness.shuffle(result);
        return result;
    }

    // ScratchBlocks formatting helpers - delegate to utility class

    /**
     * Wraps a Script in scratchblocks tags.
     *
     * @param node the script
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(Script node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps a ProcedureDefinition in scratchblocks tags.
     *
     * @param node the procedure
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(ProcedureDefinition node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps a StmtList in scratchblocks tags.
     *
     * @param node the statement list
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(StmtList node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps a statement in inline scratchblocks tags.
     *
     * @param node the statement
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(Stmt node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps an expression in inline scratchblocks tags.
     *
     * @param node the expression
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(Expression node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps a variable in variable tags.
     *
     * @param node the variable
     * @return formatted variable string
     */
    protected String wrappedScratchBlocks(Variable node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps a number literal in inline scratchblocks tags with grey ring.
     *
     * @param node the number literal
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(NumberLiteral node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Wraps a string literal in inline scratchblocks tags with context-appropriate styling.
     *
     * @param node the string literal
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(StringLiteral node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node, inLookStmt, inSoundStmt, inBroadcastStmt);
    }

    /**
     * Wraps a color literal in inline scratchblocks tags with grey ring.
     *
     * @param node the color literal
     * @return formatted scratchblocks string
     */
    protected String wrappedScratchBlocks(ColorLiteral node) {
        return ScratchBlocksFormatUtil.wrappedScratchBlocks(node);
    }

    /**
     * Creates a simplified version of a statement (control structures without body).
     *
     * @param stmt the statement
     * @return simplified statement
     */
    protected Stmt getSingleStmt(Stmt stmt) {
        return ScratchBlocksFormatUtil.getSingleStmt(stmt);
    }
}
